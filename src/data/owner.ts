/**
 * Хто юридично відповідає за обробку персональних даних.
 *
 * ⚠️ ПОТРІБНО ЗАПОВНИТИ. Ці дані не можна вигадати — вони мають збігатися
 * з вашою реєстрацією. Поки поля порожні, на сторінці /personalni-dani
 * замість них стоїть назва сервісу, і документ лишається неповним.
 *
 *   legalName — як записано у реєстрації: «ФОП Прізвище Імʼя По батькові»
 *   registry  — «РНОКПП 1234567890» або «ЄДРПОУ 12345678»
 *   address   — адреса, за якою вас можна знайти офіційно
 *   email     — пошта для звернень щодо даних; на неї писатимуть із
 *               вимогою видалити дані, тож вона має читатись
 */
export const owner = {
  legalName: "",
  registry: "",
  address: "",
  email: "",
} as const;

/** Назва для документів: реєстраційна, якщо вказана, інакше назва сервісу */
export function ownerName(fallback: string): string {
  return owner.legalName.trim() || fallback;
}
