import { describe, expect, it } from "vitest";
import { phoneKey } from "@/db/clients";

/**
 * Телефон у базі записаний по-різному: то з «+380», то з «0», то з пробілами
 * чи дужками. Якщо ключ рахується неправильно, одна людина розпадається на
 * кількох клієнтів — і позначка «постійний» більше не спрацьовує.
 */
describe("phoneKey: один клієнт — один ключ", () => {
  it("однаковий номер у різних записах дає той самий ключ", () => {
    const forms = [
      "+380733150238",
      "380733150238",
      "0733150238",
      "073 315 02 38",
      "(073) 315-02-38",
      "073-315-02-38",
      " +38 073 315 02 38 ",
    ];

    const keys = new Set(forms.map(phoneKey));
    expect(keys.size, `розпалось на ${keys.size} ключів: ${[...keys]}`).toBe(1);
    expect([...keys][0]).toBe("733150238");
  });

  it("різні номери дають різні ключі", () => {
    expect(phoneKey("+380733150238")).not.toBe(phoneKey("+380631164377"));
  });

  it("надто короткий номер ключа не має", () => {
    expect(phoneKey("12345")).toBeNull();
    expect(phoneKey("")).toBeNull();
    expect(phoneKey(null)).toBeNull();
    expect(phoneKey(undefined)).toBeNull();
  });

  it("розділювачі й пробіли не ламають розбір", () => {
    expect(phoneKey("073.315.02.38")).toBe("733150238");
    expect(phoneKey("\t073 315 02 38\n")).toBe("733150238");
  });

  it("відома межа: зайві цифри в кінці дають інший ключ", () => {
    // Ключ — останні дев'ять цифр рядка. Якщо в поле дописали внутрішній
    // номер, той самий клієнт розпадеться на двох. У реальних даних такого
    // не траплялось: номер приходить з поля type="tel". Якщо почне
    // траплятись — треба вирізати саме телефонну послідовність, а не хвіст.
    expect(phoneKey("073 315 02 38 дод. 5")).not.toBe(phoneKey("073 315 02 38"));
  });
});
